import { test,expect } from '@playwright/test'

test('用户填写与测试模型，刷新保留，会话隔离，清除立即生效',async({page,browser},testInfo)=>{
  const tests:unknown[]=[]
  await page.route('**/api/ai/test',route=>{tests.push(route.request().postDataJSON());return route.fulfill({json:{message:'连接成功'}})})
  await page.goto('/settings')
  const panel=page.locator('#ai-settings')
  await expect(panel).toContainText('待填写')
  await panel.getByLabel('API Key',{exact:true}).fill('test-key-for-settings')
  await panel.getByLabel('模型名称',{exact:true}).fill('test-model')
  await expect(panel.getByLabel('API Key',{exact:true})).toHaveAttribute('type','password')
  await panel.getByRole('button',{name:'显示 API Key',exact:true}).click()
  await expect(panel.getByLabel('API Key',{exact:true})).toHaveAttribute('type','text')
  await panel.getByRole('button',{name:'隐藏 API Key',exact:true}).click()
  await panel.getByRole('button',{name:'测试连接',exact:true}).click()
  await expect(panel.getByRole('status')).toContainText('连接成功')
  expect(tests).toEqual([{provider:'deepseek',credentials:{apiKey:'test-key-for-settings',model:'test-model'}}])
  expect(await page.evaluate(()=>sessionStorage.getItem('gujian-model-credentials'))).toBeNull()
  await panel.getByRole('button',{name:'保存配置',exact:true}).click()
  await expect(panel.getByRole('status')).toContainText('配置已保存')
  expect(await page.evaluate(()=>JSON.stringify(localStorage))).not.toContain('test-key-for-settings')
  await page.reload()
  await expect(panel.getByLabel('API Key',{exact:true})).toHaveValue('test-key-for-settings')
  await expect(panel).toContainText('本标签页已填写')
  const otherContext=await browser.newContext()
  try{const other=await otherContext.newPage();await other.goto('http://127.0.0.1:4173/settings');await expect(other.getByLabel('API Key',{exact:true})).toHaveValue('')}finally{await otherContext.close()}
  await panel.getByLabel('模型服务商').selectOption('ark')
  await expect(panel.getByLabel('API Key',{exact:true})).toHaveValue('')
  await panel.getByLabel('API Key',{exact:true}).fill('ark-test-key')
  await panel.getByLabel('模型名称 / 接入点 ID').fill('ep-test')
  await panel.getByRole('button',{name:'保存配置',exact:true}).click()
  await panel.getByLabel('模型服务商').selectOption('deepseek')
  await expect(panel.getByLabel('API Key',{exact:true})).toHaveValue('test-key-for-settings')
  await panel.getByRole('button',{name:'清除配置',exact:true}).click()
  await expect(panel.getByLabel('API Key',{exact:true})).toHaveValue('')
  await page.reload()
  await expect(panel.getByLabel('API Key',{exact:true})).toHaveValue('')
  expect(await page.evaluate(()=>JSON.parse(sessionStorage.getItem('gujian-model-credentials')||'{}').ark.model)).toBe('ep-test')
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
  await panel.screenshot({path:testInfo.outputPath('model-settings.png'),animations:'disabled'})
})

test('模型连接失败不保存，存储被禁用时不显示保存成功',async({page})=>{
  await page.route('**/api/ai/test',route=>route.fulfill({status:502,json:{error:'鉴权失败，请检查 API Key 与模型权限'}}))
  await page.goto('/settings')
  const panel=page.locator('#ai-settings')
  await panel.getByLabel('API Key',{exact:true}).fill('bad-test-key')
  await panel.getByLabel('模型名称',{exact:true}).fill('test-model')
  await panel.getByRole('button',{name:'测试连接',exact:true}).click()
  await expect(panel.getByRole('alert')).toContainText('鉴权失败')
  expect(await page.evaluate(()=>sessionStorage.getItem('gujian-model-credentials'))).toBeNull()
  await page.evaluate(()=>{Storage.prototype.setItem=function(){throw new DOMException('Blocked','SecurityError')}})
  await panel.getByRole('button',{name:'保存配置',exact:true}).click()
  await expect(panel.getByRole('alert')).toContainText('浏览器禁止会话存储')
  await expect(panel.getByRole('status')).toHaveCount(0)
})
