test('盘面导航、筛选、观察名单持久化、依据展开与研究弹窗',async({page},testInfo)=>{
  await setup(page)
  await page.goto('/')
  await page.getByRole('link',{name:'盘面选股',exact:true}).click()
  await expect(page.getByRole('link',{name:'盘面选股',exact:true})).toHaveAttribute('aria-current','page')
  await expect(page.locator('.candidate-card')).toHaveCount(2)
  await page.locator('.candidate-details summary').first().click()
  await expect(page.locator('.candidate-evidence').first()).toBeVisible()
  await expect(page.locator('.candidate-evidence').first()).toContainText('大盘偏弱')
  await page.getByRole('button',{name:'加入观察',exact:true}).first().click()
  await expect(page.getByRole('button',{name:'已加入观察',exact:true})).toHaveAttribute('aria-pressed','true')
  await expect(page.getByRole('status')).toContainText('已加入观察：牧原股份')
  await page.getByRole('button',{name:'影视院线',exact:true}).click()
  await expect(page.locator('.candidate-card')).toHaveCount(1)
  await expect(page.locator('.candidate-card')).toContainText('光线传媒')
  await page.getByRole('button',{name:'全部候选',exact:true}).click()
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
  await page.screenshot({path:testInfo.outputPath('market.png'),fullPage:true,animations:'disabled'})
  await page.reload()
  await expect(page.getByRole('button',{name:'已加入观察',exact:true})).toBeVisible()
  await page.locator('.watch-filter').click()
  await expect(page.locator('.candidate-card')).toHaveCount(1)
  await expect(page.locator('.watchlist-tray')).toContainText('牧原股份')
  await page.getByRole('button',{name:'基本面与 AI 研究'}).click()
  await expect(page.getByRole('dialog')).toContainText('牧原股份 · 公司研究')
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  expect(await page.evaluate(()=>localStorage.getItem('a-share-holdings'))).toBeNull()
})
test('行情失败可重试，不用虚构候选补位',async({page})=>{
  await setup(page)
  await page.route('**/api/market*',route=>route.fulfill({status:502,json:{error:'盘面行情暂不可用'}}))
  await page.goto('/market')
  await expect(page.getByRole('alert')).toContainText('盘面行情暂不可用')
  await expect(page.locator('.candidate-card')).toHaveCount(0)
  await page.getByRole('button',{name:'打开 Skill 研究',exact:true}).click()
  await expect(page.getByText('请输入有效的沪深 A 股代码，如 000651。')).toBeVisible()
  await page.getByLabel('研究股票代码').fill('000651')
  await page.getByRole('button',{name:'打开 Skill 研究',exact:true}).click()
  await expect(page.getByRole('dialog')).toContainText('SZ000651 · 公司研究')
  await page.keyboard.press('Escape')
  await page.route('**/api/market*',route=>route.fulfill({json:{...snapshot,candidates:[]}}))
  await page.getByRole('button',{name:'重试',exact:true}).click()
  await expect(page.getByText('暂无符合条件的候选',{exact:true})).toBeVisible()
})

test('候选 Skill 可切换，资料检查不调用 AI，AI 请求不含持仓',async({page},testInfo)=>{
  await page.addInitScript(()=>sessionStorage.setItem('gujian-model-credentials',JSON.stringify({deepseek:{apiKey:'browser-test-key',model:'test-model'}})))
  await setup(page)
  await page.route('**/api/ai/config',route=>route.fulfill({json:{providers:[{id:'deepseek',name:'DeepSeek',model:'test-model',configured:true}]}}))
  const calls:Record<string,unknown>[]=[]
  await page.route('**/api/research/analyze',route=>{
    const body=route.request().postDataJSON();calls.push(body)
    return route.fulfill({json:{code:body.code,name:'牧原股份',skill:{id:body.skill,name:body.skill==='risk'?'反向风险核查':'短线量价复核',version:'test-version',origin:'项目自定义流程'},mode:body.mode,generatedAt:'2026-11-13T06:00:00Z',marketAsOf:'2026-11-13T06:00:00Z',reportDate:null,checks:[{label:'公告与趋势核实',level:'missing',detail:'未读取公告，不能认定无利空。'}],gaps:['历史 K 线未取得'],sources:[],...(body.mode==='ai'?{content:'## 反向证据\n市场偏弱，等待持续性验证。',provider:'DeepSeek',model:'test-model'}:{})}})
  })
  await page.goto('/market')
  await page.getByRole('button',{name:'基本面与 AI 研究'}).first().click()
  const panel=page.getByRole('region',{name:'Skill 研究',exact:true})
  await expect(panel.getByRole('button',{name:/短线量价复核/})).toHaveAttribute('aria-pressed','true')
  await panel.getByText(/查看 Skill 内容与版本/).click()
  await expect(panel.locator('pre')).toContainText('规则分')
  await panel.getByRole('button',{name:'运行资料检查',exact:true}).click()
  await expect(panel.locator('.skill-check')).toContainText('未读取公告')
  expect(calls).toEqual([{code:'SZ002714',skill:'tape',mode:'checks'}])
  await panel.getByRole('button',{name:/反向风险核查/}).click()
  await expect(panel.locator('.skill-result')).toHaveCount(0)
  await panel.getByRole('button',{name:'按 Skill 生成 AI 解读',exact:true}).click()
  await expect(panel.locator('.analysis-prose')).toContainText('等待持续性验证')
  expect(calls[1]).toEqual({code:'SZ002714',skill:'risk',mode:'ai',provider:'deepseek',credentials:{apiKey:'browser-test-key',model:'test-model'}})
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
  await page.getByRole('dialog').screenshot({path:testInfo.outputPath('skill-research.png'),animations:'disabled'})
})
